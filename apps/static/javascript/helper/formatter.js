// FORMAT RUPIAH | START
// **************************************************************
function formatRupiah(value) {

      return Number(value).toLocaleString("id-ID", {
          style: "currency",
          currency: "IDR",
          minimumFractionDigits: 0,
      });
  
  }
  // **************************************************************
  // FORMAT RUPIAH | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT NUMBER | START
  // **************************************************************
  function formatNumber(value) {
  
      return Number(value).toLocaleString("id-ID");
  
  }
  // **************************************************************
  // FORMAT NUMBER | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT PHONE NUMBER | START
  // **************************************************************
  function formatPhone(phoneNumber) {
  
      return phoneNumber
          .replace(/\s+/g, "")
          .replace(/-/g, "");
  
  }
  // **************************************************************
  // FORMAT PHONE NUMBER | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT PLATE NUMBER | START
  // **************************************************************
  function formatPlate(plateNumber) {
  
      return plateNumber
          .trim()
          .toUpperCase();
  
  }
  // **************************************************************
  // FORMAT PLATE NUMBER | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT TITLE | START
  // **************************************************************
  function formatTitle(text) {
  
      return text
          .trim()
          .toLowerCase()
          .replace(/\b\w/g, char => char.toUpperCase());
  
  }
  // **************************************************************
  // FORMAT TITLE | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT UPPERCASE | START
  // **************************************************************
  function formatUpper(text) {
  
      return text
          .trim()
          .toUpperCase();
  
  }
  // **************************************************************
  // FORMAT UPPERCASE | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT LOWERCASE | START
  // **************************************************************
  function formatLower(text) {
  
      return text
          .trim()
          .toLowerCase();
  
  }
  // **************************************************************
  // FORMAT LOWERCASE | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT DATE | START
  // **************************************************************
  function formatDate(timestamp) {
  
      return new Date(timestamp * 1000)
          .toLocaleDateString("id-ID");
  
  }
  // **************************************************************
  // FORMAT DATE | END
  // **************************************************************
  
  
  // **************************************************************
  // FORMAT DATETIME | START
  // **************************************************************
  function formatDateTime(timestamp) {
  
      return new Date(timestamp * 1000)
          .toLocaleString("id-ID");
  
  }
  // **************************************************************
  // FORMAT DATETIME | END
  // **************************************************************