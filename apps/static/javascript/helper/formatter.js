// **************************************************************
// FORMAT DATE | START
// **************************************************************
function formatDate(timestamp) {
  if (!timestamp) {
    return "-";
  }

  return new Date(timestamp * 1000).toLocaleDateString("id-ID");
}
// **************************************************************
// FORMAT DATE | END
// **************************************************************

// **************************************************************
// FORMAT DATETIME | START
// **************************************************************
function formatDateTime(timestamp) {
  if (!timestamp) {
    return "-";
  }
  return new Date(timestamp * 1000).toLocaleString("id-ID");
}
// **************************************************************
// FORMAT DATETIME | END
// **************************************************************

